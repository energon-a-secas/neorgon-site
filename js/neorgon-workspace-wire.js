// ── Tools ────────────────────────────────────────────────────
// The tools that ship the kit: subdomain and the name a page shows. Generated by
// sync-workspace.sh from workspace/adopters.txt: edit that list, never these lines.
export const ADOPTERS = Object.freeze(['rama', 'floorplan', 'reparto', 'loadout', 'clientsays']) // generated by sync-workspace.sh from adopters.txt
export const TOOL_NAMES = Object.freeze({ rama: 'Rama', floorplan: 'Floorplan', reparto: 'Reparto', loadout: 'Loadout', clientsays: 'Client Says' }) // generated by sync-workspace.sh from adopters.txt

/** The name a page shows for a tool id ("Client Says"), or '' when it is not an adopter. */
export const toolName = (id) => (typeof id === 'string' && ADOPTERS.includes(id) ? own(TOOL_NAMES, id) || '' : '')

// ── Origins ──────────────────────────────────────────────────
export const WORKSPACE_ORIGIN = 'https://neorgon.com'
export const DEV_WORKSPACE_ORIGIN = 'http://localhost:8800'
export const WORKSPACE_PATH = '/workspace/'           // the page: review, pick, edit
export const VAULT_PATH = '/workspace/vault.html'     // the read-only frame

export const isLocalHost = (hostname) => hostname === 'localhost' || hostname === '127.0.0.1'

/** http://localhost:<port> or http://127.0.0.1:<port>, exactly, port 1 to 65535. */
export function isLocalOrigin(origin) {
  const m = typeof origin === 'string' && /^http:\/\/(localhost|127\.0\.0\.1):([1-9]\d{0,4})$/.exec(origin)
  return !!m && Number(m[2]) <= 65535
}

/**
 * The exact allowlist the frame answers and the Workspace page returns to:
 * https://neorgon.com, https://www.neorgon.com, https://<adopter>.neorgon.com.
 * When the checking page is itself on localhost or 127.0.0.1 (pass its
 * hostname), any local http origin too, for development only.
 */
export function originAllowed(origin, { selfHostname = '', adopters = ADOPTERS } = {}) {
  if (typeof origin !== 'string' || origin.length > 100) return false
  if (origin === 'https://neorgon.com' || origin === 'https://www.neorgon.com') return true
  const m = /^https:\/\/([a-z0-9-]{1,63})\.neorgon\.com$/.exec(origin)
  if (m && m[1] !== 'www' && Array.isArray(adopters) && adopters.includes(m[1])) return true
  return isLocalHost(selfHostname) && isLocalOrigin(origin)
}

/**
 * A return URL the Workspace page may follow, as a canonical href without its
 * fragment, or '' (show it as text, never follow). The fragment is the tool's
 * own state, which its client keeps in sessionStorage, so it never travels.
 */
export function safeReturnUrl(url, opts = {}) {
  const bare = withoutFragment(url)
  if (!bare || bare.length > 2048) return ''
  let u
  try { u = new URL(bare) } catch { return '' }
  if ((u.protocol !== 'https:' && u.protocol !== 'http:') || u.username || u.password) return ''
  if (!originAllowed(u.origin, opts)) return ''
  u.hash = ''
  return u.href
}

/** The text before the first #, or '' for a non-string: a fragment is the tool's own state and never counts toward a length cap. */
function withoutFragment(url) {
  if (typeof url !== 'string' || url.length > MAX_LINK) return ''
  const i = url.indexOf('#')
  return i < 0 ? url : url.slice(0, i)
}

/**
 * True when a return URL is where `tool` lives: https://<tool>.neorgon.com on
 * the fleet, any local origin in development. Binds the name a page shows
 * ("Share with Client Says") to where it sends the workspace.
 */
export function returnFitsTool(returnUrl, tool) {
  let u
  try { u = new URL(returnUrl) } catch { return false }
  if (isLocalOrigin(u.origin)) return true
  return typeof tool === 'string' && /^[a-z0-9-]{1,63}$/.test(tool) && u.origin === `https://${tool}.neorgon.com`
}

/**
 * Where a tool finds the Workspace page and its frame: neorgon.com on any
 * neorgon.com host; on localhost, the dev origin a test stored (only a local
 * origin is honoured) or localhost:8800; '' anywhere else (no workspace).
 */
export function workspaceOrigin({ hostname = '', devOrigin = '' } = {}) {
  if (isNeorgonHost(hostname)) return WORKSPACE_ORIGIN
  if (isLocalHost(hostname)) return isLocalOrigin(devOrigin) ? devOrigin : DEV_WORKSPACE_ORIGIN
  return ''
}

// ── Payloads in links ────────────────────────────────────────
async function deflateRaw(bytes) {
  const stream = new Blob([bytes]).stream().pipeThrough(new CompressionStream('deflate-raw'))
  return new Uint8Array(await new Response(stream).arrayBuffer())
}

/**
 * j1. + base64url of UTF-8 JSON; z1. + base64url of deflate-raw when the
 * browser has CompressionStream and the result is shorter. Rejects only when
 * the value cannot be JSON (a cycle, a BigInt): it is the writer's own data.
 */
export async function encodePayload(value, { compress = true } = {}) {
  const bytes = utf8(JSON.stringify(value))
  const plain = 'j1.' + toBase64Url(bytes)
  if (compress && typeof CompressionStream === 'function') {
    try {
      const packed = 'z1.' + toBase64Url(await deflateRaw(bytes))
      if (packed.length < plain.length) return packed
    } catch { /* no deflate-raw in this browser: the plain form is always readable */ }
  }
  return plain
}

const PAYLOAD = /^[jz]1\.[A-Za-z0-9_-]+$/
/** True for text shaped like a payload (prefix, base64url, within MAX_PAYLOAD); says nothing about what it holds. */
export const isPayloadText = (s) => typeof s === 'string' && s.length <= MAX_PAYLOAD && PAYLOAD.test(s)

/** The parsed JSON of a j1. or z1. payload, or null. Synchronous; the core's decodePayload normalizes it. */
export function unpackPayload(text) {
  if (typeof text !== 'string' || text.length > MAX_PAYLOAD) return null
  const m = /^(j1|z1)\.([A-Za-z0-9_-]+)$/.exec(text.trim())
  if (!m) return null
  let bytes = fromBase64Url(m[2])
  if (!bytes) return null
  if (m[1] === 'z1') { try { bytes = inflateRaw(bytes) } catch { return null } }
  const json = fromUtf8(bytes)
  if (json == null) return null
  try { return JSON.parse(json) } catch { return null }
}

// ── Round trips: the three fragments ─────────────────────────
//   <page>#save=<payload>&tool=<id>&return=<url>   a tool asks the page to review and save
//   <page>#pick&tool=<id>&return=<url>             a tool asks for the visitor's team
//   <return>#neo-ws=<payload>&stamp=<stamp>        the page's answer to a pick
// A payload and a stamp need no escaping; the return URL is percent-encoded,
// so neither & nor # inside it can end a field. Every value is checked again
// on the way in: a fragment is whatever the address bar holds.

/** A tool's own address without the fragment: what it sends as `return`. */
export function returnUrlOf(href) {
  const bare = withoutFragment(href)
  if (!bare || bare.length > 2048) return ''
  try {
    const u = new URL(bare)
    if (u.protocol !== 'https:' && u.protocol !== 'http:') return ''
    u.hash = ''
    return u.href
  } catch { return '' }
}

const pageOrigin = (o) => o === WORKSPACE_ORIGIN || isLocalOrigin(o)
function pageLink(origin, head, tool, returnUrl, max) {
  const back = returnUrlOf(returnUrl)
  if (!pageOrigin(origin) || !ADOPTERS.includes(tool) || !back) return ''
  const link = `${origin}${WORKSPACE_PATH}#${head}&tool=${tool}&return=${encodeURIComponent(back)}`
  return link.length <= max ? link : ''
}

/** The Workspace page's review for a save, or '' when an input is bad or the link would pass `max` (then offer a file). */
export function saveLink({ origin, payload, tool, returnUrl, max = MAX_LINK } = {}) {
  return isPayloadText(payload) ? pageLink(origin, `save=${payload}`, tool, returnUrl, max) : ''
}

/** The Workspace page's pick screen, or '' when an input is bad. */
export const pickLink = ({ origin, tool, returnUrl, max = MAX_LINK } = {}) => pageLink(origin, 'pick', tool, returnUrl, max)

/**
 * Where the page sends the visitor after a pick: the return URL with its
 * fragment replaced (never appended to) by #neo-ws=<payload>&stamp=<stamp>.
 * '' when the URL is not allowed (opts as safeReturnUrl), an input is bad, or
 * the link would pass `max`.
 */
export function answerLink(returnUrl, { payload, stamp = '' } = {}, { max = MAX_LINK, ...opts } = {}) {
  const back = safeReturnUrl(returnUrl, opts)
  if (!back || !isPayloadText(payload) || (stamp !== '' && !isStamp(stamp))) return ''
  const link = `${back}#neo-ws=${payload}${stamp ? `&stamp=${stamp}` : ''}`
  return link.length <= max ? link : ''
}

const FIELDS = { save: ['tool', 'return'], pick: ['tool', 'return'], 'neo-ws': ['stamp'] }
/**
 * A fragment the kit wrote, read strictly, or null for anything else (unknown
 * or repeated fields, a tool not in the list, a malformed payload or stamp):
 *   { op: 'save', payload, tool, returnUrl, returnText }
 *   { op: 'pick', tool, returnUrl, returnText }
 *   { op: 'answer', payload, stamp }
 * returnUrl is '' when the page may not follow it (opts as safeReturnUrl) or
 * it is not the named tool's own address (returnFitsTool);
 * returnText is the address as given, cleaned and capped, to show instead.
 * The payload is still only text: previewPayload or decodePayload reads it.
 */
export function parseFragment(hash, { selfHostname = '', adopters = ADOPTERS } = {}) {
  if (typeof hash !== 'string' || hash.length > MAX_PAYLOAD + 4200) return null
  const [head, ...rest] = hash.replace(/^#/, '').split('&').map((part) => {
    const i = part.indexOf('=')
    return i < 0 ? [part, null] : [part.slice(0, i), part.slice(i + 1)]
  })
  const [op, value] = head
  if (!Object.prototype.hasOwnProperty.call(FIELDS, op) || (op === 'pick') !== (value === null)) return null
  const got = new Map()
  for (const [k, v] of rest) {
    if (!FIELDS[op].includes(k) || got.has(k) || v === null) return null
    got.set(k, v)
  }
  if (op === 'neo-ws') {
    const stamp = got.get('stamp') ?? ''
    return isPayloadText(value) && (stamp === '' || isStamp(stamp)) ? { op: 'answer', payload: value, stamp } : null
  }
  const tool = got.get('tool')
  if (!Array.isArray(adopters) || !adopters.includes(tool) || (op === 'save' && !isPayloadText(value))) return null
  let text = got.get('return') ?? ''
  try { text = decodeURIComponent(text) } catch { /* shown as given, never followed */ }
  // The return must be the named tool's own address, or a page could say "Share with Floorplan" and send to Rama.
  const allowed = safeReturnUrl(text, { selfHostname, adopters })
  const out = { op, tool, returnUrl: allowed && returnFitsTool(allowed, tool) ? allowed : '', returnText: str(text, 300) }
  if (op === 'save') out.payload = value
  return out
}

// ── The read-only frame (postMessage) ────────────────────────
// Parent to frame: { ns, id, op: 'ping' | 'get' }. The frame answers
// { ns, id, ok: true, status, stamp } and, for get, ws too; any other op gets
// { ns, id, ok: false, error: 'read-only' }; on a storage event it pushes
// { ns, op: 'changed', status, stamp, ws }. The origin check is the caller's:
// originAllowed(event.origin) in the frame, event.origin and event.source in the client.
export const PROTOCOL = 'neo-workspace/1'
export const FRAME_TIMEOUT = 1500                       // ms without an answer means no frame
export const FRAME_STATUSES = Object.freeze(['shared', 'stale', 'empty'])

const isRequestId = (id) => (typeof id === 'string' && /^[A-Za-z0-9_-]{1,64}$/.test(id)) || (Number.isSafeInteger(id) && id >= 0)

/** What a client posts to the frame, or null for a bad id or op. */
export const frameRequest = (id, op) => (isRequestId(id) && (op === 'ping' || op === 'get') ? { ns: PROTOCOL, id, op } : null)

/** A parent's message as the frame reads it: { id, op } with op 'ping', 'get' or 'refused' (answer read-only), or null (not ours: no answer at all). */
export function readRequest(data) {
  if (!isMap(data) || own(data, 'ns') !== PROTOCOL || !isRequestId(own(data, 'id'))) return null
  const op = own(data, 'op')
  return { id: own(data, 'id'), op: op === 'ping' || op === 'get' ? op : 'refused' }
}

const status = (s) => (FRAME_STATUSES.includes(s) ? s : 'empty')
const stampOf = (s) => (isStamp(s) ? s : '')

/** The frame's answer to a ping (no ws) or a get (pass the stored ws, or null when there is none). */
export function frameReply(request, { status: s, stamp, ws = null } = {}) {
  const out = { ns: PROTOCOL, id: request.id, ok: true, status: status(s), stamp: stampOf(stamp) }
  if (request.op === 'get') out.ws = isMap(ws) ? ws : null
  return out
}

/** The frame's answer to anything that is not ping or get. */
export const frameRefusal = (request) => ({ ns: PROTOCOL, id: request.id, ok: false, error: 'read-only' })

/** What the frame pushes to its parent when another tab saved. */
export const frameChanged = ({ status: s, stamp, ws = null } = {}) => ({ ns: PROTOCOL, op: 'changed', status: status(s), stamp: stampOf(stamp), ws: isMap(ws) ? ws : null })
